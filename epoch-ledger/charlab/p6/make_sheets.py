"""P6 comparison sheets (PIL): one sheet per stylisation variant, an A/B/C overview, and the measured proportions.

    python3 epoch-ledger/charlab/p6/make_sheets.py projects/charlab_p6
Reads views_{A,B,C}/ (render_p6.py), ortho_{raw,A,B,C}/ (ortho_p6.py) and measurements.json (build_p6.py).
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

D = Path(sys.argv[1])
F, FR = "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf", "/usr/share/fonts/opentype/inter/Inter-Regular.otf"
font = lambda s, b=False: ImageFont.truetype(F if b else FR, s)
M = json.load(open(D / "measurements.json"))
GOLD, TXT, DIM, BG = "#f2c66d", "#e8e8ea", "#9a9ca3", "#15171c"
NAMES = {"A": "A · subtle mature stylisation", "B": "B · balanced editorial stylisation", "C": "C · stronger cinematic illustrated stylisation"}
VIEWS = [("full_front", "full body · front"), ("full_side", "full body · side"), ("face_front", "face · front"),
         ("face_34", "face · three-quarter"), ("face_side", "face · profile")]


def std_line(v):
    m = M[v]
    ok = lambda c: "pass" if c else "FAIL"
    return (f"{m['heads_tall']} heads ({ok(7.0 <= m['heads_tall'] <= 8.0)}) · shoulders {m['shoulder_width_hh']} head heights "
            f"({ok(m['shoulder_width_hh'] >= 1.5)}) · eye width {m['eye_w_over_head_w'] * 100:.1f}% of head ({ok(m['eye_w_over_head_w'] <= 0.24)})")


def recipe(v):
    m = M[v]
    return (f"geometry: anatomical morphs (age, jaw, zygomatic, chin, shoulders) + relief simplification {m['smooth']} it + plane "
            f"accentuation {m['accent']} + head scale {m['head_scale']}")


def row(v, H):
    ims = [Image.open(D / f"views_{v}" / f"{k}.png").convert("RGB") for k, _ in VIEWS]
    ims = [im.resize((round(im.width * H / im.height), H), Image.LANCZOS) for im in ims]
    return ims


def variant_sheet(v):
    H = 760; ims = row(v, H); W = sum(i.width for i in ims) + 12 * (len(ims) - 1) + 60
    img = Image.new("RGB", (W, H + 250), BG); d = ImageDraw.Draw(img)
    d.text((30, 22), f"P6 mature stylised prototype — {NAMES[v]}", font=font(36, True), fill=GOLD)
    d.text((30, 72), std_line(v), font=font(22), fill=TXT)
    d.text((30, 102), recipe(v), font=font(20), fill=DIM)
    x = 30
    for im, (_, lab) in zip(ims, VIEWS):
        img.paste(im, (x, 140)); d.text((x + 8, 146), lab, font=font(20, True), fill="#ffffff"); x += im.width + 12
    d.text((30, H + 160), "Same base (CharMorph Reom, CC-BY), wardrobe, hair, lights, cameras and exposure for every variant. Neutral "
           "expression; neutral grey studio; Cycles CPU, 64 samples, denoised.", font=font(19), fill=DIM)
    d.text((30, H + 190), "Static visual prototype: posed by linear-blend skinning with the base's Rigify weights; not rigged or "
           "animated. Wardrobe and hair are procedural meshes generated by build_p6.py.", font=font(19), fill=DIM)
    img.save(D / f"sheet_{v}.png")


def overview():
    H = 430; rows = {v: row(v, H) for v in "ABC"}; W = 330 + sum(i.width for i in rows["A"]) + 10 * 4 + 20
    img = Image.new("RGB", (W, 100 + 3 * (H + 20) + 40), BG); d = ImageDraw.Draw(img)
    d.text((24, 22), "P6 — three controlled geometric stylisations of one mature base (same wardrobe, hair, light, cameras)",
           font=font(32, True), fill=GOLD)
    for k, v in enumerate("ABC"):
        y = 90 + k * (H + 20); d.text((24, y + 10), NAMES[v].split(" · ")[0], font=font(64, True), fill=GOLD)
        for j2, ln in enumerate(NAMES[v].split(" · ")[1].replace(" stylisation", "").split(" ", 1) if v == "C" else [NAMES[v].split(" · ")[1]]):
            d.text((24, y + 90 + 24 * j2), ln, font=font(20, True), fill=TXT)
        m = M[v]
        for j, t in enumerate([f"{m['heads_tall']} heads", f"shoulders {m['shoulder_width_hh']} hh", f"eyes {m['eye_w_over_head_w'] * 100:.1f}% of head",
                               f"accent {m['accent']} · head ×{m['head_scale']}"]):
            d.text((24, y + 150 + 28 * j), t, font=font(20), fill=DIM)
        x = 330
        for im in rows[v]: img.paste(im, (x, y)); x += im.width + 10
    img.save(D / "sheet_overview.png")


def proportions():
    cols = ["raw", "A", "B", "C"]; ph = 1000; pxm = ph / 2.1
    img = Image.new("RGB", (40 + len(cols) * 2 * 290 + 40, ph + 330), BG); d = ImageDraw.Draw(img)
    d.text((24, 18), "P6 measured proportions — orthographic, one scale (body only, wardrobe and hair hidden), head-height grid",
           font=font(28, True), fill=GOLD)
    x = 30
    for v in cols:
        m = M[v]; hh = m["head_height_m"]; Hm = m["height_m"]
        for side in ("front", "side"):
            im = Image.open(D / f"ortho_{v}" / f"ortho_{side}.png").convert("RGB"); im = im.crop((135, 0, 425, ph))
            img.paste(im, (x, 70)); dd = ImageDraw.Draw(img)
            for k in range(0, 9):
                zpx = 70 + ph - (Hm - k * hh) * pxm
                if zpx < 70 + ph: dd.line([(x, zpx), (x + 289, zpx)], fill="#f2c66d" if k == 0 else "#5d6270", width=1)
            x += 290
        d.text((x - 560, ph + 80), "raw Reom (unchanged base)" if v == "raw" else NAMES[v].split(" · ")[0] + " · " + NAMES[v].split(" · ")[1].split(" stylisation")[0],
               font=font(22, True), fill=GOLD if v != "raw" else TXT)
        for j, t in enumerate([f"height {Hm:.3f} m · head {hh:.3f} m", f"{m['heads_tall']} heads tall", f"biacromial {m['biacromial_m']:.3f} m = {m['shoulder_width_hh']} hh",
                               f"head width {m['head_width_m']:.3f} m", f"eye opening {m['eye_width_m'] * 1000:.1f} mm = {m['eye_w_over_head_w'] * 100:.1f}% of head"]):
            d.text((x - 560, ph + 115 + 28 * j), t, font=font(20), fill=DIM)
    d.text((24, ph + 280), "Standard (CHARACTER_STANDARD.md): 7.0–8.0 heads (7.5 preferred) · men's shoulders ≥ 1.5 head heights (1.6–1.8 typical) · eye width ≤ 24% of head width. "
           "Definitions as convert/measure_props.py.", font=font(19), fill=DIM)
    img.save(D / "sheet_proportions.png")


for v in "ABC": variant_sheet(v)
overview(); proportions()
print("sheets written to", D)
